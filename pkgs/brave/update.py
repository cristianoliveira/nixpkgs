#!/usr/bin/env python3
"""Update Brave to the latest stable GitHub release and its published hashes."""
import base64
import json
import os
from pathlib import Path
import re
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parent
BASE = "https://github.com/brave/brave-browser/releases/download"
ASSETS = {
    "aarch64-linux": "brave-browser_${version}_arm64.deb",
    "x86_64-linux": "brave-browser_${version}_amd64.deb",
    "aarch64-darwin": "Brave-Browser-arm64.dmg",
    "x86_64-darwin": "Brave-Browser-x64.dmg",
}


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "conixpkgs-brave-update"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read().decode("utf-8")


def render(version, checksums):
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
        raise ValueError("invalid release version")
    lines = ["# Generated by update.py. Do not edit by hand.", "rec {", '  pname = "brave";', f'  version = "{version}";', "  archives = {"]
    for system, filename in ASSETS.items():
        checksum = checksums[system].split()[0]
        if not re.fullmatch(r"[0-9a-fA-F]{64}", checksum):
            raise ValueError(f"invalid checksum for {system}")
        digest = base64.b64encode(bytes.fromhex(checksum)).decode("ascii")
        lines.extend([f"    {system} = {{", f'      url = "{BASE}/v${{version}}/{filename}";', f'      hash = "sha256-{digest}";', "    };"])
    lines.extend(["  };", "}", ""])
    return "\n".join(lines)


def main():
    release = json.loads(fetch("https://api.github.com/repos/brave/brave-browser/releases/latest"))
    if release.get("prerelease") or release.get("draft"):
        raise ValueError("latest release is not stable")
    tag = release["tag_name"]
    if not re.fullmatch(r"v[0-9]+\.[0-9]+\.[0-9]+", tag):
        raise ValueError("invalid release tag")
    version = tag[1:]
    checksums = {system: fetch(f"{BASE}/{tag}/{filename.replace('${version}', version)}.sha256") for system, filename in ASSETS.items()}
    output = render(version, checksums)
    with tempfile.NamedTemporaryFile(mode="w", dir=ROOT, delete=False) as f:
        temporary = Path(f.name)
        try:
            f.write(output)
        except BaseException:
            temporary.unlink(missing_ok=True)
            raise
    try:
        os.replace(temporary, ROOT / "release.nix")
    finally:
        temporary.unlink(missing_ok=True)
    print(f"Updated Brave to {tag}; build and test each platform before publishing.")


if __name__ == "__main__":
    main()
